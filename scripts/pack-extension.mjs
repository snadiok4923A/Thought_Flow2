#!/usr/bin/env node
// Build a distributable ThoughtFlow AI Capture extension zip with a
// hosted capture API baked in (zero-config for end users).
//
// Usage:
//   node scripts/pack-extension.mjs --api https://<your-app>.onrender.com/api --token <CAPTURE_TOKEN>
//   HOSTED_API_BASE=https://<your-app>.onrender.com/api HOSTED_TOKEN=<token> node scripts/pack-extension.mjs
//
// Output:
//   dist-extension/thoughtflow-capture/   (load-unpacked folder)
//   dist-extension/thoughtflow-capture.zip (share / upload to Web Store)
//
// The hosted apiBase + token are written into hosted-config.js and the
// hosted origin is added to manifest.json host_permissions, so a fresh
// install talks to the hosted API with no Settings needed. Users can
// still override both in popup → Settings (chrome.storage.sync wins).
//
// NOTE: the token is embedded in the zip and in the website JS — anyone
// who extracts them can see it. Use a strong random token, keep the
// server rate limit on (default 30/min/IP), and rotate the token if
// the API is ever abused. Fine for personal / small-team use.

import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.join(root, "chrome-extension");
const outRoot = path.join(root, "dist-extension");
const outDir = path.join(outRoot, "thoughtflow-capture");
const zipPath = path.join(outRoot, "thoughtflow-capture.zip");

function arg(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : "";
}

const apiBase = (
  arg("--api") ||
  process.env.HOSTED_API_BASE ||
  process.env.VITE_CAPTURE_API_BASE ||
  ""
).trim();
const token = (arg("--token") || process.env.HOSTED_TOKEN || process.env.VITE_CAPTURE_TOKEN || "").trim();

if (!apiBase || !token) {
  console.error(
    "Missing hosted API config. Pass --api and --token, or set HOSTED_API_BASE / HOSTED_TOKEN.\n" +
      "Example: node scripts/pack-extension.mjs --api https://my-app.onrender.com/api --token <token>"
  );
  process.exit(1);
}

if (!/^https:\/\//.test(apiBase)) {
  console.error(`Hosted API base must be an https:// URL (got: ${apiBase})`);
  process.exit(1);
}

const apiClean = apiBase.replace(/\/+$/, "");
const origin = new URL(apiClean).origin; // e.g. https://my-app.onrender.com
const hostPerm = `${origin}/*`;

console.log(`Packing extension with hosted API: ${apiClean}`);

// Fresh copy of the extension folder (test harness excluded — not shipped).
fs.rmSync(outDir, { recursive: true, force: true });
fs.cpSync(srcDir, outDir, {
  recursive: true,
  filter: (src) => !src.includes(`${path.sep}test${path.sep}`) && !src.endsWith(`${path.sep}test`),
});

// Bake hosted defaults into hosted-config.js.
const hostedConfig = `// Hosted defaults — generated by scripts/pack-extension.mjs. Do not edit by hand.
// Users can still override both values in popup → Settings.
globalThis.TF_HOSTED_CONFIG = {
  apiBase: ${JSON.stringify(apiClean)},
  token: ${JSON.stringify(token)},
};
`;
fs.writeFileSync(path.join(outDir, "hosted-config.js"), hostedConfig);

// Add the hosted origin to host_permissions (MV3 fetch needs it).
const manifestPath = path.join(outDir, "manifest.json");
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
manifest.host_permissions = manifest.host_permissions || [];
if (!manifest.host_permissions.includes(hostPerm)) {
  manifest.host_permissions.push(hostPerm);
}
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

// Zip it (uses the system `zip` CLI — available on macOS/Linux/WSL;
// on Windows use Git Bash or PowerShell's Compress-Archive instead).
fs.rmSync(zipPath, { force: true });
try {
  execSync(`zip -r -q "${zipPath}" thoughtflow-capture`, { cwd: outRoot, stdio: "inherit" });
} catch {
  console.error(
    "\n`zip` CLI not found. The load-unpacked folder is ready at:\n" +
      `  ${outDir}\nZip it manually (or use Compress-Archive in PowerShell) to share it.`
  );
  process.exit(0);
}

console.log(`\nDone:\n  Folder: ${outDir}\n  Zip:    ${zipPath}\n`);
console.log("Share the zip (Drive / GitHub Release / Web Store). End users: unzip →");
console.log("chrome://extensions → Developer mode → Load unpacked → select the folder. Done.");
